    b=p.chromium.launch(); pg=b.new_page(viewport={'width':1366,'height':860})
    pg.goto("http://127.0.0.1:5173/login"); pg.wait_for_selector("text=Inicia sesión")
    pg.fill("input[type=email]","admin@demo.test"); pg.fill("input[type=password]","DemoClave123"); pg.click("button:has-text('Entrar')")
    pg.wait_for_selector("text=Hola, Admin")
    pg.click("nav >> text=Empresas"); pg.wait_for_selector("td >> text=Andina Logística")
    ok("menú Empresas lista las empresas reales", True)
    pg.click("button:has-text('Nueva empresa') >> nth=0"); pg.click("button:has-text('Crear empresa')")
    ok("validación de campos obligatorios", pg.locator("text=Escribe el nombre comercial").count()==1)
    f=pg.locator("[role=dialog]")
    f.locator("input").nth(0).fill("Ferretería El Tornillo"); f.locator("input").nth(1).fill("901555000-1"); f.locator("input").nth(2).fill("Comercio")
    f.locator("input[type=email]").fill("ventas@tornillo.co"); f.locator("input").nth(5).fill("Cali")
    pg.click("button:has-text('Crear empresa')"); pg.wait_for_selector("td >> text=Ferretería El Tornillo")
    ok("crear empresa", True)
    pg.click("button:has-text('Nueva empresa') >> nth=0"); f=pg.locator("[role=dialog]")
